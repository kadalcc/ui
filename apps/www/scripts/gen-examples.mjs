#!/usr/bin/env node
/**
 * Generates src/components/docs/ExampleHost.astro: a static import of every example under
 * registry/kadal/examples/, so <Demo name="…"> can hydrate one by name. Astro needs hydrated
 * components to be statically imported, which is why a glob isn't enough. Runs before dev and
 * build; run it by hand after adding an example (`bun run gen:examples`).
 */
import { readdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { basename, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const dir = resolve(root, "registry/kadal/examples");
const out = resolve(root, "src/components/docs/ExampleHost.astro");

const names = readdirSync(dir)
  .filter((f) => f.endsWith(".tsx"))
  .map((f) => basename(f, ".tsx"))
  .sort();

const ident = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

const file = `---
/* GENERATED by scripts/gen-examples.mjs. Do not edit; add a file to registry/kadal/examples/ and
   run \`bun run gen:examples\`. Each example is its own static tag: Astro can only hydrate a
   component it can see imported and used by name. */
${names.map((n) => `import ${ident(n)} from "@/registry/kadal/examples/${n}";`).join("\n")}

interface Props {
  name: string;
  props?: Record<string, unknown>;
}
const { name, props = {} } = Astro.props;
const known = new Set(${JSON.stringify(names)});
if (!known.has(name)) throw new Error(\`No example named "\${name}" in registry/kadal/examples/ (run bun run gen:examples).\`);
---

${names.map((n) => `{name === "${n}" && <${ident(n)} client:visible {...props} />}`).join("\n")}
`;

if (!existsSync(out) || readFileSync(out, "utf8") !== file) {
  writeFileSync(out, file);
  console.log(`ExampleHost.astro: ${names.length} examples`);
}
